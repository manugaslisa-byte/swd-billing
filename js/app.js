/* ======================================================================
   app.js - start-up: login, menu, drawing the current screen, install as app
   ====================================================================== */

/* ---------- screen state (shared with views.js) ---------- */
let user = null;               // { name, role } after login
let tab = 'dash';              // which screen is open
let pageHistory = [];
let selected = null;           // account number picked in Meter Reading / Payments
let lastBill = null;           // bill just generated (shown with print buttons)
let lastReceipt = null;        // receipt just generated
let lastBulkReceipts = [];     // receipts generated by paying multiple months together
let selectedBillNo = null;     // individual monthly bill selected for payment
let payAllOutstanding = false;
let reprintText = '';          // bill/receipt chosen for reprint in Records
let recordsTab = 'bills';      // Records: 'bills' or 'payments'
let installEvent = null;       // browser's "install app" offer
let loginError = '';

// What each role may open
const MENU = {
  admin:   ['dash', 'customers', 'read', 'pay', 'turnover', 'deposit', 'archive', 'records', 'settings'],
  reader:  ['dash', 'customers', 'read', 'archive', 'records', 'profile'],
  teller:  ['dash', 'customers', 'pay', 'turnover', 'archive', 'records', 'reports', 'profile'],
  cashier: ['dash', 'deposit', 'archive', 'records', 'reports', 'profile']
};
const TAB_NAMES = {
  dash: 'Dashboard', customers: 'Consumers', read: 'Meter Reading', pay: 'Payments',
  turnover: 'Turn Over', deposit: 'Deposits', archive: 'Archive', records: 'Records', reports: 'Reports', settings: 'Settings', profile: 'My Profile'
};

/* ---------- keep the user logged in when the page is refreshed ----------
   The login is kept in sessionStorage: it survives a refresh, and it is
   erased when the user logs out or closes the tab / the installed app. */
const SESSION_KEY = 'swd-session';
const TERMS_VERSION = '1.0';
const TERMS_ACCEPTANCE_KEY = 'swd-terms-acceptance';

function saveSession() {
  try {
    if (user) sessionStorage.setItem(SESSION_KEY, JSON.stringify({ user, tab }));
    else sessionStorage.removeItem(SESSION_KEY);
  } catch (e) { /* storage blocked: the user simply logs in again after a refresh */ }
}

function restoreSession() {
  try {
    const saved = JSON.parse(sessionStorage.getItem(SESSION_KEY) || 'null');
    if (!saved || !saved.user) return;
    const known = Object.values(USERS).some(u => u.name === saved.user.name && u.role === saved.user.role);
    if (!known || sessionExpiredOnRefresh()) return;                                           // account no longer exists
    const match = Object.values(USERS).find(u => u.name === saved.user.name && u.role === saved.user.role);
    user = { username: match.username, name: match.name, role: match.role };
    tab = MENU[user.role].includes(saved.tab) ? saved.tab : 'dash';
  } catch (e) { user = null; }
}

/* ---------- login ---------- */
function login(event) {
  event.preventDefault();
  const usernameInput = $('#u');
  const passwordInput = $('#w');
  if (!usernameInput.value.trim() || !passwordInput.value) {
    loginError = 'Enter your username and password.';
    render();
    return;
  }
  const username = $('#u').value.trim().toLowerCase();
  const password = $('#w').value;
  if (username.length < 5 || username.length > 15 || password.length < 8 || password.length > 10) {
    loginError = 'Username must be 5–15 characters and password must be 8–10 characters.';
    render();
    return;
  }
  if (!$('#termsAccepted').checked) {
    loginError = 'Read and accept the Terms & Conditions to continue.';
    $('#loginError').textContent = loginError;
    $('#termsAccepted').focus();
    return;
  }
  const lockedFor = loginLockMinutes(username);
  if (lockedFor) {
    audit('LOGIN BLOCKED', username, 'login temporarily locked', false, username);
    loginError = `Too many wrong attempts. Try again in ${lockedFor} minute(s).`;
    render();
    return;
  }
  const account = USERS[username];
  if (!account || account.password !== password) {
    const nowLocked = recordLoginFailure(username, !!account);
    loginError = nowLocked ? `Too many wrong attempts. This login is locked for ${LOCK_MINUTES} minutes.` : 'Wrong username or password.';
    render();
    return;
  }
  try {
    const acceptances = JSON.parse(localStorage.getItem(TERMS_ACCEPTANCE_KEY) || '[]');
    acceptances.push({
      username,
      role: account.role,
      version: TERMS_VERSION,
      acceptedAt: new Date().toISOString()
    });
    localStorage.setItem(TERMS_ACCEPTANCE_KEY, JSON.stringify(acceptances));
  } catch (e) {
    loginError = 'Could not save your Terms & Conditions acceptance on this device.';
    render();
    return;
  }
  loginError = '';
  user = { username: account.username, name: account.name, role: account.role };
  tab = 'dash';
  pageHistory = [];
  touchActivity();
  recordLoginSuccess(account);
  saveSession();
  render();
}

function handleLoginKeydown(event) {
  if (event.key === 'Enter' && (event.target.id === 'u' || event.target.id === 'w')) {
    event.preventDefault();
    login(event);
  }
}

function logout() { if (user) audit('LOGOUT', user.username); user = null; tab = 'dash'; pageHistory = []; selected = lastBill = lastReceipt = selectedBillNo = null; lastBulkReceipts = []; payAllOutstanding = false; reprintText = ''; consumerRecordAccount = null; saveSession(); render(); }

function openTerms() {
  $('#termsDialog').showModal();
}

function closeTerms() {
  $('#termsDialog').close();
}

function togglePasswordVisibility(inputId, button) {
  const input = document.getElementById(inputId);
  if (!input) return;
  const visible = input.type === 'password';
  input.type = visible ? 'text' : 'password';
  button.setAttribute('aria-label', visible ? 'Hide password' : 'Show password');
  button.title = visible ? 'Hide password' : 'Show password';
}

function go(name) {
  if (!MENU[user.role].includes(name)) return;
  if (name !== tab) rememberCurrentPage();
  tab = name;
  saveSession();
  selected = lastBill = lastReceipt = selectedBillNo = null;
  lastBulkReceipts = [];
  payAllOutstanding = false;
  reprintText = '';
  consumerRecordAccount = null;
  render();
}

function rememberCurrentPage() {
  pageHistory.push({ tab, consumerRecordAccount });
}

function goBack() {
  let previous;
  while (pageHistory.length && !previous) {
    const candidate = pageHistory.pop();
    if (MENU[user.role].includes(candidate.tab)) previous = candidate;
  }
  if (!previous) return;
  tab = previous.tab;
  consumerRecordAccount = previous.consumerRecordAccount;
  selected = lastBill = lastReceipt = selectedBillNo = null;
  lastBulkReceipts = [];
  payAllOutstanding = false;
  reprintText = '';
  saveSession();
  render();
}

/* ---------- "Install app" button ---------- */
window.addEventListener('beforeinstallprompt', event => {
  event.preventDefault();
  installEvent = event;
  render();
});
const installButton = () => installEvent
  ? '<button type="button" class="s" style="margin:0 8px 0 0" onclick="installEvent.prompt();installEvent=null;render()">Install app</button>' : '';

/* ---------- draw the page ---------- */
